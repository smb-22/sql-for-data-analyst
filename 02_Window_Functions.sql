SELECT *FROM USERWATCHDATA

---> ROW_NMBER()

SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
ROW_NUMBER() OVER(PARTITION BY PLATFORM ORDER BY WATCHMINUTE DESC) AS ROW_NUM
FROM USERWATCHDATA

---> AGGREGATE WINDOW FUNCTIONS
SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
SUM(WATCHMINUTE) OVER(PARTITION BY USERNAME ORDER BY WATCHDATE) AS RUNNING_TOTAL
FROM USERWATCHDATA



SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
AVG(WATCHMINUTE) OVER(PARTITION BY USERNAME ORDER BY WATCHDATE) AS RUNNING_TOTAL
FROM USERWATCHDATA

SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
MAX(WATCHMINUTE) OVER(PARTITION BY PLATFORM) AS MAX_WATCH
FROM USERWATCHDATA


SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
MIN(WATCHMINUTE) OVER(PARTITION BY PLATFORM) AS MIN_WATCH
FROM USERWATCHDATA


---> RANK() AND DENSE_RANK():


SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
RANK() OVER(PARTITION BY PLATFORM ORDER BY WATCHMINUTE DESC) AS RANKNUM
--DENSE_RANK() OVER(PARTITION BY PLATFORM ORDER BY WATCHMINUTE DESC) AS DENSEDRANKNUM
FROM USERWATCHDATA

SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
--RANK() OVER(PARTITION BY PLATFORM ORDER BY WATCHMINUTE DESC) AS RANKNUM
DENSE_RANK() OVER(PARTITION BY PLATFORM ORDER BY WATCHMINUTE DESC) AS DENSEDRANKNUM
FROM USERWATCHDATA

--> LEAD() AND LAG() FUNCTIONS:

SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
LAG(WATCHMINUTE) OVER( ORDER BY WATCHDATE) AS PREVIOUSVALUE
FROM USERWATCHDATA


SELECT USERNAME, PLATFORM, WATCHDATE, WATCHMINUTE,
LEAD(WATCHMINUTE) OVER( PARTITION BY USERNAME ORDER BY WATCHDATE) AS NEXTVALUE
FROM USERWATCHDATA
