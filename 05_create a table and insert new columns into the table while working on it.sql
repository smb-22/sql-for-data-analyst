SELECT EMPID, DEPTNAME, SALARY,'HIGH PAID' AS LABEL
FROM EMP
WHERE SALARY > 15000 
UNION
SELECT EMPID, DEPTNAME, SALARY,'LOW PAID' AS LABEL
FROM EMP

SELECT DEPTNAME,
       SALARY,
       CASE
           WHEN salary >= 15000 THEN 'High'
           WHEN salary <= 15000 THEN 'Low'
           ELSE 'Medium'
       END AS salary_category
FROM EMP;


