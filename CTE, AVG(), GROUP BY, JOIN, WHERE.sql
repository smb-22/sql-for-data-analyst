FROM HIGH_SALARY;

--> CTE with GROUP BY
---> Calculate Avg salary for each dept.

WITH DEPT_AVG AS(
    SELECT DEPTID,
            AVG(SALARY) AS AVG_SALARY
    FROM EMP
    GROUP BY DEPTID
)
SELECT * FROM DEPT_AVG
ORDER BY DEPTID

---> FIND EMPLOYEES EARNING MORE THAN THEIR DEPARTMENT'S AVG SALARY
WITH DEPT_AVG AS(
    SELECT DEPTID,
            AVG(SALARY) AS AVG_SALARY
    FROM EMP
    GROUP BY DEPTID
)
SELECT E.EMPNAME,E.DEPTID, E.SALARY, D.AVG_SALARY
FROM EMP E
JOIN DEPT_AVG D
    ON E.DEPTID = D.DEPTID
WHERE E.SALARY > D.AVG_SALARY
ORDER BY E.DEPTID, E.SALARY DESC;


